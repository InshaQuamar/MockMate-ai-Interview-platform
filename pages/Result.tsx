
import React, { useEffect, useState } from 'react';
import { useInterview } from '../context/InterviewContext';
// Fix: Import from local backend api service instead of purged interviewEngine
import { generatePerformanceFeedback as getSessionFeedback } from '../backend/api';
import { PieChart, Pie, Cell, ResponsiveContainer, BarChart, Bar, XAxis, YAxis, Tooltip } from 'recharts';

const Result: React.FC = () => {
  const { session, resetSession } = useInterview();
  const [sessionReview, setSessionReview] = useState<string | null>(null);
  const [loadingReview, setLoadingReview] = useState(true);

  useEffect(() => {
    if (session && session.endTime) {
      const fetchReview = async () => {
        setLoadingReview(true);
        const attempted = Object.keys(session.answers).length;
        const feedback = await getSessionFeedback(attempted, session.totalQuestions, session.type);
        setSessionReview(feedback);
        setLoadingReview(false);
      };
      fetchReview();
    }
  }, [session]);

  if (!session) return null;

  const attemptedCount = Object.keys(session.answers).length;
  const skippedCount = session.skipped.length;
  const score = Math.round((attemptedCount / session.totalQuestions) * 100);

  const pieData = [
    { name: 'Completed', value: attemptedCount },
    { name: 'Missed', value: skippedCount },
  ];

  const barData = [
    { name: 'My Index', value: score },
    { name: 'Industry Avg', value: 65 },
  ];

  const COLORS = ['#3b82f6', '#ef4444'];

  const getPerformanceMessage = () => {
    if (score >= 80) return { text: "Outstanding performance. You meet placement benchmarks.", color: "text-green-500", bg: "bg-green-500/10", border: "border-green-500/20" };
    if (score >= 50) return { text: "Solid attempt. Refine technical specifics for better consistency.", color: "text-yellow-500", bg: "bg-yellow-500/10", border: "border-yellow-500/20" };
    return { text: "Further preparation required. Recommend intensive module review.", color: "text-red-500", bg: "bg-red-500/10", border: "border-red-500/20" };
  };

  const msg = getPerformanceMessage();

  return (
    <div className="min-h-screen pt-32 pb-24 flex flex-col items-center px-6">
      <div className="max-w-5xl w-full space-y-8 animate-in fade-in zoom-in-95 duration-700">
        
        <div className="text-center space-y-2">
          <h2 className="text-4xl font-extrabold text-white tracking-tighter uppercase italic">Session Summary</h2>
          <p className="text-gray-400">Data-driven performance report generated by InterviewAce Analysis Engine.</p>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
          <div className="md:col-span-2 glass p-8 rounded-3xl border border-white/5 space-y-8">
            <div className="flex flex-col md:flex-row items-center gap-10">
              <div className="relative w-48 h-48">
                <ResponsiveContainer width="100%" height="100%">
                  <PieChart>
                    <Pie
                      data={pieData}
                      cx="50%"
                      cy="50%"
                      innerRadius={60}
                      outerRadius={80}
                      paddingAngle={5}
                      dataKey="value"
                    >
                      {pieData.map((entry, index) => (
                        <Cell key={`cell-${index}`} fill={COLORS[index % COLORS.length]} />
                      ))}
                    </Pie>
                  </PieChart>
                </ResponsiveContainer>
                <div className="absolute inset-0 flex flex-col items-center justify-center">
                  <span className="text-4xl font-black text-white">{score}%</span>
                  <span className="text-[10px] text-gray-500 uppercase font-black tracking-widest">Efficiency</span>
                </div>
              </div>

              <div className="flex-1 space-y-6">
                <div className={`p-4 rounded-2xl border ${msg.bg} ${msg.border} text-center md:text-left shadow-lg`}>
                  <p className={`font-black text-sm uppercase tracking-widest mb-1 opacity-60 ${msg.color}`}>Verdict</p>
                  <p className={`font-bold text-lg leading-snug ${msg.color}`}>{msg.text}</p>
                </div>
                
                <div className="grid grid-cols-3 gap-4">
                  <div className="text-center p-4 bg-white/5 rounded-2xl border border-white/5">
                    <div className="text-2xl font-bold text-white">{session.totalQuestions}</div>
                    <div className="text-[10px] text-gray-500 uppercase font-black tracking-widest">Questions</div>
                  </div>
                  <div className="text-center p-4 bg-white/5 rounded-2xl border border-white/5">
                    <div className="text-2xl font-bold text-blue-500">{attemptedCount}</div>
                    <div className="text-[10px] text-gray-500 uppercase font-black tracking-widest">Completed</div>
                  </div>
                  <div className="text-center p-4 bg-white/5 rounded-2xl border border-white/5">
                    <div className="text-2xl font-bold text-red-500">{skippedCount}</div>
                    <div className="text-[10px] text-gray-500 uppercase font-black tracking-widest">Bypassed</div>
                  </div>
                </div>
              </div>
            </div>

            <div className="pt-6 border-t border-white/10 space-y-4">
              <div className="flex items-center gap-2">
                <span className="text-xl">📊</span>
                <h4 className="text-lg font-bold text-white">Engine Performance Review</h4>
              </div>
              <div className="p-6 bg-blue-500/5 rounded-2xl border border-blue-500/10 min-h-[100px] flex items-center justify-center">
                {loadingReview ? (
                  <div className="flex flex-col items-center gap-3">
                    <div className="w-8 h-8 border-3 border-blue-500 border-t-transparent rounded-full animate-spin"></div>
                    <span className="text-gray-500 text-sm animate-pulse tracking-widest uppercase font-black">Syncing Review Data...</span>
                  </div>
                ) : (
                  <p className="text-gray-300 leading-relaxed italic font-medium">"{sessionReview}"</p>
                )}
              </div>
            </div>
          </div>

          <div className="space-y-6">
            <div className="glass p-6 rounded-3xl border border-white/5 min-h-[250px] flex flex-col justify-between">
              <h3 className="font-bold text-white mb-4 tracking-widest uppercase text-xs opacity-60">Benchmark Comparison</h3>
              <div className="h-40 w-full">
                <ResponsiveContainer width="100%" height="100%">
                  <BarChart data={barData}>
                    <XAxis dataKey="name" axisLine={false} tickLine={false} tick={{fill: '#9ca3af', fontSize: 10, fontWeight: 'bold'}} />
                    <Tooltip cursor={{fill: 'transparent'}} contentStyle={{backgroundColor: '#111827', border: 'none', borderRadius: '8px', color: '#fff'}} />
                    <Bar dataKey="value" fill="#3b82f6" radius={[4, 4, 0, 0]} barSize={40} />
                  </BarChart>
                </ResponsiveContainer>
              </div>
              <p className="text-[10px] text-gray-500 mt-4 text-center font-bold uppercase tracking-tighter">Your stats vs. Tier-1 Placement Entry Requirements.</p>
            </div>

            <div className="flex flex-col gap-3">
              <button 
                onClick={resetSession}
                className="w-full py-4 bg-blue-600 hover:bg-blue-500 text-white rounded-2xl font-black transition-all shadow-xl shadow-blue-500/20"
              >
                Re-take Interview
              </button>
              <button 
                onClick={resetSession}
                className="w-full py-4 bg-white/5 hover:bg-white/10 text-white border border-white/10 rounded-2xl font-bold transition-all"
              >
                Dashboard
              </button>
            </div>
          </div>
        </div>

        <div className="space-y-4 pt-8">
          <h3 className="text-xl font-bold text-white uppercase tracking-tighter italic">Recent Activity</h3>
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            <HistoryCard date="Live Session" type={session.type} score={score} />
            <HistoryCard date="Oct 24, 2023" type="HR" score={92} />
            <HistoryCard date="Oct 20, 2023" type="Backend" score={45} />
          </div>
        </div>
        
        <footer className="mt-12 py-8 border-t border-white/5 text-center">
          <p className="text-gray-500 text-xs font-medium">
            Designed and Developed by <span className="text-blue-500 font-bold">Insha Quamar</span>
          </p>
        </footer>
      </div>
    </div>
  );
};

const HistoryCard = ({ date, type, score }: { date: string, type: string, score: number }) => (
  <div className="glass p-5 rounded-2xl border border-white/5 flex items-center justify-between">
    <div className="space-y-1">
      <div className="text-[10px] text-gray-500 font-black uppercase tracking-widest">{date}</div>
      <div className="text-white font-bold">{type}</div>
    </div>
    <div className={`text-xl font-black ${score >= 80 ? 'text-green-500' : score >= 50 ? 'text-yellow-500' : 'text-red-500'}`}>
      {score}%
    </div>
  </div>
);

export default Result;
